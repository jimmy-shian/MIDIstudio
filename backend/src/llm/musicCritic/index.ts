/** Music Critic：完成後的品質檢查與修改方向。 */
export const MUSIC_CRITIC_GUIDELINES = `
完成後以更新後工程依序檢查：
1. 需求/意圖：明確要求、既有工程連續性、情緒表達是否保留？
2. 結構：段落功能、能量、高點、結尾與總小節數是否清楚正確？
3. 素材：核心動機是否可辨認；重複是否建立記憶、變化是否推進發展？
4. 張力：累積是否有方向，高點及釋放是否相稱；若刻意懸而未決，是否聽得出是意圖？
5. 編曲/演奏：聲部角色、音域和密度是否平衡；旋律、跳進、句長、休止、重音和力度是否自然？
6. 工程：beats、小節、音高、velocity、track 與操作回報是否合理，是否只改到預期範圍？

分級處理：先修阻礙需求/表達的問題，再修明顯可聽性問題；可選潤飾僅在收益明確時做。每輪只改最重要的一至兩項，修改後重查。需求已滿足且無重大問題就停止；遇工具能力限制要明確說出。`;

/** 要求模型在已套用工程更新後，以 Critic 身分檢視結果再決定是否續作。 */
export function buildCriticReviewInstruction(appliedReports: string[]): string {
  return `Critic 檢查：先根據目前更新後的工程，依序檢查需求/意圖、結構與長度、核心素材及變化、張力與釋放、編曲與演奏性、工程正確性。剛完成的操作：${appliedReports.join("；") || "無"}。只修正會明顯損害需求或可聽性的問題，每次最多處理一至兩項；若沒有重大問題或需求已滿足，直接用中文總結並停止，不要為修改而修改。`;
}
